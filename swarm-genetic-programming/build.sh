#!/bin/sh
# Builds the Rust engine to wasm and embeds it as base64 in swarm_wasm.js,
# so index.html loads it with a plain <script> (works from file://).
set -e
cd "$(dirname "$0")"
cargo build --release --target wasm32-unknown-unknown --manifest-path rust/Cargo.toml
WASM=rust/target/wasm32-unknown-unknown/release/swarm_gp.wasm
node -e '
const fs = require("fs");
const b64 = fs.readFileSync(process.argv[1]).toString("base64");
fs.writeFileSync("swarm_wasm.js", "// generated by build.sh from rust/ - do not edit\nglobalThis.SWARM_WASM_BASE64 = \"" + b64 + "\";\n");
console.log("swarm_wasm.js:", b64.length, "base64 chars");
' "$WASM"
